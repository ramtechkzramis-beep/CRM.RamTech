-- «Наработки» — промежуточный статус между холодной базой и текущими
-- клиентами: компания, с которой уже была встреча и которая готова
-- работать с нами на 70-80%. Переход в обе стороны (cold <-> warm)
-- делает обычный сотрудник вручную, без отдельных RPC-функций —
-- обычный update, права те же, что и на остальные поля клиента.
alter type client_status add value 'warm';
